import { readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join } from 'node:path'
import { createElement } from 'react'
import { renderToStaticMarkup } from 'react-dom/server'
import * as icons from '@phosphor-icons/react/ssr'
import { format } from 'prettier'

// Only these locally installed, trusted components are evaluated at generation time.
const names = [
  'ArrowsSplit',
  'BracketsCurly',
  'FolderLock',
  'Gauge',
  'Graph',
  'Handshake',
  'ListChecks',
  'ListMagnifyingGlass',
  'Monitor',
  'Receipt',
  'RocketLaunch',
  'Scales',
  'SealCheck',
  'UserCheck',
  'UserFocus',
  'Warning',
]
const data = Object.fromEntries(
  names.map((name) => {
    const svg = renderToStaticMarkup(createElement(icons[name], { weight: 'regular' }))
    const match = /^<svg[^>]*viewBox="([^"]+)"[^>]*>([\s\S]*)<\/svg>$/.exec(svg)
    if (!match) throw new Error(`Unexpected SVG from ${name}`)
    return [
      name.replace(/[A-Z]/g, (char, index) => `${index ? '-' : ''}${char.toLowerCase()}`),
      { viewBox: match[1], body: match[2] },
    ]
  }),
)
const require = createRequire(import.meta.url)
const root = join(dirname(require.resolve('@phosphor-icons/react')), '..')
const license = readFileSync(join(root, 'LICENSE'), 'utf8')
const brandNotices = readFileSync('licenses/TheSVG-NOTICES.md', 'utf8')
const source = await format(
  `// Generated by scripts/generate-semantic-icons.mjs; do not edit.\n// Phosphor regular icons, MIT license preserved in semanticIconLicense.\nimport type { SemanticNodeIconKey } from '../types'\nexport const semanticIcons = ${JSON.stringify(data)} satisfies Record<SemanticNodeIconKey, {viewBox:string;body:string}>\nexport const semanticIconLicense = ${JSON.stringify(license)}\nexport const brandIconNotices = ${JSON.stringify(brandNotices)}\n`,
  { parser: 'typescript', singleQuote: true, semi: false, printWidth: 100 },
)
const path = 'src/brand-icons/semantic-data.ts'
if (process.argv.includes('--check')) {
  if (readFileSync(path, 'utf8') !== source) throw new Error('Semantic icon assets out of sync')
} else writeFileSync(path, source)
